import { env } from '../env';

/**
 * AI assistance status. Zenvora ships with NO AI provider configured: every
 * "assist" feature must call `getAiStatus()` first and fall back to the
 * deterministic helpers below when `enabled` is false. Nothing in this module
 * contacts a network service, invents model output, or changes approval
 * policy — AI can propose, never approve (see docs/AUTONOMOUS_OPERATIONS.md).
 */
export interface AiStatus {
  enabled: false;
  provider: null;
  reason: string;
  /** What the UI should say instead of pretending a model answered. */
  fallback: 'DETERMINISTIC';
}

export function getAiStatus(): AiStatus {
  // No AI_* variables exist in the validated environment schema (src/lib/env.ts).
  // When an owner decides to add a provider, extend envSchema first, then this
  // function — never read process.env ad hoc here.
  void env;
  return {
    enabled: false,
    provider: null,
    reason:
      'No AI provider is configured for this deployment. Assist features use deterministic rules; nothing is generated by a model.',
    fallback: 'DETERMINISTIC',
  };
}

/**
 * Deterministic title clean-up used where an "AI title suggestion" would
 * otherwise sit: trims, collapses whitespace, strips supplier noise tokens and
 * caps length. Pure and reversible to inspect — no invented attributes.
 */
export function deterministicTitleCleanup(raw: string, maxLength = 90): string {
  const noise = /\b(free shipping|hot sale|new arrival|dropshipping|wholesale|2026|2025|2024)\b/gi;
  const cleaned = raw
    .replace(/[\u{1F300}-\u{1FAFF}\u{2600}-\u{27BF}]/gu, ' ')
    .replace(noise, ' ')
    .replace(/\s{2,}/g, ' ')
    .replace(/\s+([,.;:])/g, '$1')
    .trim();
  if (cleaned.length <= maxLength) return cleaned;
  const cut = cleaned.slice(0, maxLength);
  const lastSpace = cut.lastIndexOf(' ');
  return (lastSpace > maxLength * 0.6 ? cut.slice(0, lastSpace) : cut).trim();
}
